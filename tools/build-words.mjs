// Builds the shared word lists used by Spelling Bee, Strands and Letter Boxed.
// Usage: node tools/build-words.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const read = (f) => fs.readFileSync(path.join(here, "dict", f), "utf8").split(/\r?\n/).map((w) => w.trim()).filter(Boolean);

const substrings = [];
const exact = new Set();
for (const line of read("blocklist.txt")) {
  if (line.startsWith("#")) continue;
  if (line.startsWith("~")) substrings.push(line.slice(1));
  else for (const suffix of ["", "s", "es", "ed", "ing", "er", "ers", "y"]) exact.add(line + suffix);
}
const allowed = (w) => /^[a-z]+$/.test(w) && !exact.has(w) && !substrings.some((s) => w.includes(s));

const common = [...new Set(read("popular.txt").map((w) => w.toLowerCase()))].filter((w) => w.length >= 3 && w.length <= 15 && allowed(w)).sort();
const full = [...new Set(read("enable1.txt").map((w) => w.toLowerCase()))].filter((w) => w.length >= 3 && w.length <= 15 && allowed(w)).sort();

fs.mkdirSync(path.join(root, "words"), { recursive: true });
fs.writeFileSync(
  path.join(root, "words", "common.js"),
  "// Generated by tools/build-words.mjs from popular.txt (common subset of ENABLE). Do not edit by hand.\n" +
    "window.COMMON_WORDS = " + JSON.stringify(common.join(" ")) + ";\n"
);
fs.writeFileSync(path.join(root, "words", "enable.txt"), full.join("\n") + "\n");
console.log("common:", common.length, "full:", full.length);
